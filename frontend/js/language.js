const dictionary = new Map(entries);
let current = 'ru';
export const locale = () => current==='en'?'en-GB':'ru-RU';
export const t = (ru,en) => current==='en'?(en ?? dictionary.get(ru) ?? ru):ru;

export function mountLanguage(document,{request,csrf,changed,storage}) {
  const button=document.getElementById('language-toggle');
  const key='mgimov-language';
  const read=k=>{try{return storage?.getItem(k);}catch{return null;}};
  const write=(k,v)=>{try{if(v===null)storage?.removeItem(k);else storage?.setItem(k,v);}catch{}};
  let browser=read(key)==='en'?'en':'ru';
  let pendingBrowser=read(key+'-pending');
  let owner=null, epoch=0, changes=0, queue=Promise.resolve();
  const staticText=[];
  const walker=document.createTreeWalker(document.documentElement,4);
  for(let node=walker.nextNode();node;node=walker.nextNode()){
    if(dictionary.has(node.nodeValue.trim())){
      const original=node.nodeValue;
      staticText.push(()=>{node.nodeValue=original.replace(original.trim(),t(original.trim()));});
    }
  }
  for(const element of document.querySelectorAll('[aria-label],[placeholder],[title]')){
    for(const attribute of ['aria-label','placeholder','title']){
      const original=element.getAttribute(attribute);
      if(dictionary.has(original))staticText.push(()=>element.setAttribute(attribute,t(original)));
    }
  }
  function apply(language,notify=true){
    const next=language==='en'?'en':'ru';
    const different=next!==current;
    current=next;
    document.documentElement.lang=next;
    button.setAttribute('aria-label',t('Переключить язык','Switch language'));
    button.textContent=next==='en'?'RU':'EN';
    for(const update of staticText)update();
    if(different&&notify){document.dispatchEvent(new Event('mgimov:language'));changed?.();}
  }
  function save(id,language,{fromBrowser=false}={}){
    const session=epoch;
    queue=queue.catch(()=>{}).then(async()=>{
      if(session!==epoch||id!==owner)return;
      await request('/api/v1/me/language',{method:'POST',body:{language},
        headers:{'X-Mgimov-User':id,'X-CSRF-Token':csrf()}});
      if(session===epoch&&id===owner&&(fromBrowser||pendingBrowser)){
        pendingBrowser=null;
        write(key+'-pending',null);
      }
    });
    return queue;
  }
  button.addEventListener('click',()=>{
    changes++;
    const value=current==='en'?'ru':'en';
    if(owner)save(owner,value).catch(()=>{});
    else{browser=value;pendingBrowser=value;write(key,value);write(key+'-pending',value);}
    apply(value);
  });
  apply(browser,false);
  return {
    setUser(user){
      const id=user?.id??null;
      if(id===owner)return;
      owner=id;
      const session=++epoch;
      if(!id){apply(browser);return;}
      const pending=pendingBrowser;
      if(pending==='ru'||pending==='en'){
        apply(pending);save(id,pending,{fromBrowser:true}).catch(()=>{});return;
      }
      const selection=changes;
      request('/api/v1/me/language',{headers:{'X-Mgimov-User':id}})
        .then(data=>{if(session===epoch&&selection===changes&&id===owner)apply(data.language);}).catch(()=>{});
    }
  };
}
